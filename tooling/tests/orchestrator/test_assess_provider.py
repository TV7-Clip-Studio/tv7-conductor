from __future__ import annotations

import json
from pathlib import Path
import subprocess
import tempfile
import unittest
from unittest.mock import patch

from orchestrator.tickets import (
    _assess_with_cli_queue,
    _assess_with_gemini,
    _extract_json_object_from_text,
    _resolve_assess_backend,
)


class AssessProviderTests(unittest.TestCase):
    def test_auto_prefers_codex_for_local_automation(self) -> None:
        with patch("orchestrator.tickets.shutil.which", side_effect=lambda name: f"/usr/bin/{name}"):
            resolved = _resolve_assess_backend(assess_agent="auto", model="gemini-2.5-pro")
        self.assertEqual(resolved, "codex")

    def test_gemini_agent_uses_gemini_queue_when_available(self) -> None:
        def _which(name: str):
            if name == "gemini":
                return "/usr/bin/gemini"
            return None

        with patch("orchestrator.tickets.shutil.which", side_effect=_which):
            resolved = _resolve_assess_backend(assess_agent="gemini", model="gemini-2.5-pro")
        self.assertEqual(resolved, "gemini_queue")

    def test_queue_payload_uses_cli_wording_not_antigravity(self) -> None:
        with tempfile.TemporaryDirectory(prefix="tv7-assess-provider-") as td:
            core_dir = Path(td)
            item = {
                "item_id": "ST-A01-02-01",
                "title": "Assess provider wording",
                "source_file": "docs/roadmaps/tv7-astro-site-roadmap.md",
                "source_line": 15,
                "tasks": ["One task"],
            }
            _assessment, pending_path, _elapsed = _assess_with_cli_queue(
                core_dir=core_dir,
                repo="tv7-astro-site",
                item=item,
                provider="gemini",
                profile="gemini_pro_medium",
                model="gemini-2.5-pro",
                reasoning="medium",
                personality="pragmatic",
            )

            payload = json.loads(Path(pending_path).read_text())
            self.assertEqual(payload["provider"], "gemini")
            instructions = " ".join(payload.get("instructions", []))
            self.assertIn("Gemini CLI", instructions)
            self.assertIn("Codex CLI", instructions)
            self.assertNotIn("Antigravity", instructions)

    def test_extract_json_object_from_text_handles_fenced_block(self) -> None:
        raw = "```json\n{\"summary\":\"ok\",\"acceptance_criteria\":[],\"validation_commands\":[],\"risks\":[],\"notes\":[]}\n```"
        parsed = _extract_json_object_from_text(raw)
        self.assertEqual(parsed.get("summary"), "ok")

    def test_assess_with_gemini_parses_json_envelope_response(self) -> None:
        with tempfile.TemporaryDirectory(prefix="tv7-assess-provider-") as td:
            root = Path(td)
            core_dir = root / "tv7-core"
            repo_dir = root / "tv7-astro-site"
            core_dir.mkdir(parents=True, exist_ok=True)
            repo_dir.mkdir(parents=True, exist_ok=True)
            item = {
                "item_id": "ST-A01-02-01",
                "title": "Assess with gemini",
                "source_file": "docs/roadmaps/tv7-astro-site-roadmap.md",
                "source_line": 15,
                "tasks": ["One task"],
            }
            stdout_payload = json.dumps(
                {
                    "response": json.dumps(
                        {
                            "summary": "Generated by gemini",
                            "acceptance_criteria": ["AC1"],
                            "validation_commands": ["npm run lint"],
                            "risks": ["Risk1"],
                            "notes": ["Note1"],
                        }
                    )
                }
            )
            fake_run = subprocess.CompletedProcess(
                args=["gemini"],
                returncode=0,
                stdout=stdout_payload,
                stderr="",
            )
            with (
                patch("orchestrator.tickets.shutil.which", side_effect=lambda name: f"/usr/bin/{name}"),
                patch("orchestrator.tickets.subprocess.run", return_value=fake_run),
            ):
                assessment, _log, _elapsed = _assess_with_gemini(
                    core_dir=core_dir,
                    repo="tv7-astro-site",
                    item=item,
                    model="gemini-2.5-pro",
                )
            self.assertEqual(assessment["summary"], "Generated by gemini")
            self.assertIn("AC1", assessment["acceptance_criteria"])


if __name__ == "__main__":
    unittest.main()
